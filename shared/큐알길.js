/* 큐알길 — 찍은 큐알 한 줄이 **어디로 가는 길인지** 가린다.

   사장님 10-11 말씀:
   「이런 스캔의 종류가 많아 질텐데 지금이야 에이엠티의 해당명세서 한길 이지만
     다른 루트를 보여주는 큐알일때는 어떻게 해지?」

   ⚠⚠ **큐알 종류를 코드에 박지 마라.** 종류가 늘 때마다 스캔 화면을 뜯게 된다.
      가는 길은 **화베의 규칙표**(`큐알규칙`)에 줄로 쌓인다 — 새 큐알은 **줄 하나만** 더하면 된다.

   이 파일은 **셈만 한다.** 화베를 안 읽는다 —
   프로그램마다 제 파이어베이스를 들고 있으니, 줄은 부르는 쪽이 읽어서 넘긴다.
   그래야 이 파일이 SDK 에 묶이지 않고 노드에서도 그대로 잴 수 있다.

   규칙 한 줄
     꼴    찾을 본(정규식 글). 보기 `^[^\s]+-\d{8}-\d+-[A-Z]$`
     이름  단추에 보일 말.     보기 「납기 명세서」
     갈곳  갈 주소 틀.         보기 `…/에이엠티.html?명세={전체}`
           {전체} 는 찍힌 글 통째 · {1} {2} 는 꼴의 괄호로 잡은 토막
           ⚠ 넣을 때 **주소용으로 감싼다**(encodeURIComponent). 한글·빈칸이 들어와도 안 깨진다.
     차례  작은 것이 위. 없으면 100.
     끔    참이면 건너뛴다. 줄을 지우지 않고 잠시 끌 때 쓴다.

   돌려주는 것 — **맞는 길을 다 돌려준다.** 하나면 바로 가면 되고, 둘이면 고르시게 한다.
   하나도 없으면 **빈 목록**이다. 그때는 찍힌 글을 그대로 보여 드려라 —
   ⚠ **조용히 아무 일도 안 하는 것이 제일 나쁘다.**
*/
(() => {
  /* ⚠⚠ **http·https 말고는 안 연다.** 규칙표는 자료다 — 누가 `javascript:` 를 적어 넣으면
        찍는 것만으로 코드가 돈다. 여기서 한 번 막는다. 이 줄을 지우지 마라. */
  const 열수있나 = (주소) => /^https?:\/\//i.test(주소);

  const 끼우기 = (틀, 글, 잡은것) =>
    String(틀 ?? '').replace(/\{(전체|\d+)\}/g, (_, 열쇠) => {
      const 값 = 열쇠 === '전체' ? 글 : (잡은것[Number(열쇠)] ?? '');
      return encodeURIComponent(값);
    });

  /** 찍힌 글 하나로 갈 수 있는 길을 다 찾는다. [{이름, 주소, 꼴}] */
  function 풀기(글, 규칙들) {
    const 글자 = String(글 ?? '').trim();
    if (!글자) return [];
    const 밖 = [];

    /* 큐알이 그 자체로 주소인 것 — 규칙표에 없어도 연다.
       바깥에서 받은 큐알(택배·명함)이 그렇다. 규칙을 쌓을 까닭이 없다. */
    if (열수있나(글자)) 밖.push({ 이름: '그 주소 열기', 주소: 글자, 꼴: '(주소)' });

    const 줄 = (규칙들 ?? [])
      .filter((r) => r && !r.끔 && r.꼴 && r.갈곳)
      .slice()
      .sort((a, b) => (a.차례 ?? 100) - (b.차례 ?? 100));

    for (const r of 줄) {
      let 잡은것 = null;
      /* ⚠ 꼴이 하나 잘못 적혀 있다고 **스캔이 통째로 멈추면 안 된다.** 그 줄만 건너뛴다. */
      try { 잡은것 = new RegExp(r.꼴).exec(글자); } catch (e) { continue; }
      if (!잡은것) continue;
      const 주소 = 끼우기(r.갈곳, 글자, 잡은것);
      if (!열수있나(주소)) continue;                 // 위 막이 — 틀을 채운 뒤에도 다시 본다
      if (밖.some((x) => x.주소 === 주소)) continue; // 같은 곳이 두 번 뜨지 않게
      밖.push({ 이름: String(r.이름 || '열기'), 주소, 꼴: r.꼴 });
    }
    return 밖;
  }

  /* 규칙표가 사는 자리. 프로그램이 제 SDK 로 여기를 읽어 줄을 넘긴다.
     `vp_` 가 아니다 — 스캔하는 프로그램이 여럿이라 다 읽을 수 있어야 한다. */
  const 자리 = ['artifacts', 'vivivic-4b7ef', 'public', 'data', '큐알규칙'];

  const 것 = { 풀기, 자리 };
  if (typeof window !== 'undefined') window.큐알길 = 것;
  if (typeof module !== 'undefined' && module.exports) module.exports = 것;
})();
